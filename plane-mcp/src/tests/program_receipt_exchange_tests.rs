//! Receipt checks at the actual ProgramExchange caller: no child write precedes a checked first
//! host head, and a later head cannot replace it. The strict peer delegates receipt parsing and
//! launch-version stamping to production code; the connector supplies only scripted wire pieces.

use std::cell::RefCell;
use std::collections::VecDeque;
use std::task::Poll;

use base64::{engine::general_purpose::STANDARD, Engine as _};
use busbar_contract::abi::host::conn::connector::{ReplyPiece, REPLY_BODY, REPLY_HEAD};
use busbar_contract::abi::mechanism::ticket::Ticket;
use busbar_contract::abi::sdk::conn::Replied;
use busbar_contract::abi::transport::FrameSpan;
use serde_json::{json, Value};

use crate::client::jsonrpc::ServerRequestGrants;
use crate::program_trust::{self, Versions};
use crate::tool_program::{AskOwner, Exchanged, Peer, ProgramConn, ProgramExchange};

const COMMAND: &str = "/approved/receipt-child";
const MEMBER: &str = "receipt-server";
const STREAM: u64 = 23;

/// The public host receipt, independently written rather than generated by the validator.
fn receipt(command: &str) -> Vec<u8> {
    format!(
        "generation: 7\r\nprogram-instance: 37\r\nprogram-identity: {}\r\n",
        STANDARD.encode(command)
    )
    .into_bytes()
}

struct Piece {
    descriptor: ReplyPiece,
    bytes: Vec<u8>,
}

impl Piece {
    /// Put unrelated bytes around the span: the exchange must pass exactly the head's fields.
    fn head(status: u32, fields: &[u8]) -> Self {
        let mut bytes = b"outside-fields\0".to_vec();
        let offset = bytes.len() as u64;
        bytes.extend_from_slice(fields);
        bytes.extend_from_slice(b"outside-fields-again");
        Self {
            descriptor: ReplyPiece {
                kind: REPLY_HEAD,
                code: status,
                fields: FrameSpan {
                    offset,
                    len: fields.len() as u64,
                },
                ..ReplyPiece::default()
            },
            bytes,
        }
    }

    fn body(value: &Value) -> Self {
        Self {
            descriptor: ReplyPiece {
                kind: REPLY_BODY,
                ..ReplyPiece::default()
            },
            bytes: serde_json::to_vec(value).expect("a child message serialises"),
        }
    }
}

#[derive(Default)]
struct State {
    incoming: VecDeque<Piece>,
    written: Vec<Value>,
    closed: Vec<u64>,
    opened: Vec<(u32, String)>,
}

struct ScriptedConn(RefCell<State>);

impl ScriptedConn {
    fn new(pieces: impl IntoIterator<Item = Piece>) -> Self {
        Self(RefCell::new(State {
            incoming: pieces.into_iter().collect(),
            ..State::default()
        }))
    }
}

impl ProgramConn for ScriptedConn {
    fn establish(
        &self,
        _: Ticket,
        _: u32,
        need: u32,
        member: &str,
        _: u32,
    ) -> Poll<Result<u64, String>> {
        self.0.borrow_mut().opened.push((need, member.to_owned()));
        Poll::Ready(Ok(STREAM))
    }

    fn read_reply(
        &self,
        _: Ticket,
        _: u32,
        stream: u64,
        buf: &mut [u8],
        slot: &mut ReplyPiece,
    ) -> Poll<Result<Replied, String>> {
        assert_eq!(stream, STREAM);
        let Some(piece) = self.0.borrow_mut().incoming.pop_front() else {
            return Poll::Pending;
        };
        buf[..piece.bytes.len()].copy_from_slice(&piece.bytes);
        *slot = piece.descriptor;
        Poll::Ready(Ok(Replied {
            piece: *slot,
            len: piece.bytes.len(),
        }))
    }

    fn write(&self, _: Ticket, _: u32, stream: u64, bytes: &[u8]) -> Poll<Result<usize, String>> {
        assert_eq!(stream, STREAM);
        let message: Value = serde_json::from_slice(bytes).expect("one outgoing JSON message");
        let mut state = self.0.borrow_mut();
        state.written.push(message.clone());
        if let Some(id) = message.get("id") {
            let result = match message["method"].as_str() {
                Some("initialize") => {
                    json!({ "protocolVersion": "2025-06-18", "capabilities": {} })
                }
                Some("tools/list") => json!({ "tools": [{ "name": "read" }] }),
                _ => panic!("an unexpected child request"),
            };
            state.incoming.push_back(Piece::body(&json!({
                "jsonrpc": "2.0", "id": id, "result": result
            })));
        }
        Poll::Ready(Ok(bytes.len()))
    }

    fn close(&self, _: Ticket, _: u32, stream: u64) -> Poll<()> {
        self.0.borrow_mut().closed.push(stream);
        Poll::Ready(())
    }
}

#[derive(Default)]
struct StrictPeer {
    versions: Versions,
    checked: Vec<(u32, String, u32)>,
    greeted: Vec<u64>,
}

impl Peer for StrictPeer {
    fn program_generation(
        &mut self,
        need: u32,
        member: &str,
        status: u32,
        fields: &[u8],
    ) -> Result<u64, String> {
        self.checked.push((need, member.to_owned(), status));
        if need != crate::statement::NEED_PROGRAM || member != MEMBER {
            return Err(program_trust::UNTRUSTED.to_string());
        }
        let observed = program_trust::block(status, fields, COMMAND, true)?;
        self.versions.stamp(member, observed)
    }

    fn grants(&self) -> ServerRequestGrants {
        ServerRequestGrants::default()
    }

    fn claim(&mut self, _: u64, _: &Value) -> bool {
        false
    }

    fn owner(&mut self, _: u64, _: &Value) -> AskOwner {
        AskOwner::Refused
    }

    fn notice(&mut self) {}

    fn greeted(&mut self, generation: u64) {
        self.greeted.push(generation);
    }
}

fn exchange(host: &ScriptedConn, peer: &mut StrictPeer) -> Result<Exchanged, String> {
    let mut exchange =
        ProgramExchange::listing(MEMBER, crate::statement::NEED_PROGRAM, json!(91), true);
    let ticket = Ticket {
        slot: 19,
        generation: 3,
    };
    for _ in 0..32 {
        if let Poll::Ready(result) = exchange.drive(host, ticket, 0, &|_| false, peer) {
            return result;
        }
    }
    panic!("the scripted exchange did not finish");
}

/// Run the identical caller and peer with a valid receipt before relying on negative controls.
fn positive_control() {
    let host = ScriptedConn::new([Piece::head(200, &receipt(COMMAND))]);
    let mut peer = StrictPeer::default();
    let done = exchange(&host, &mut peer).expect("a valid host receipt permits the exchange");
    assert!(done.greeted);
    assert_ne!(done.generation, 0);
    assert_eq!(peer.greeted, [done.generation]);
    assert_eq!(
        peer.checked,
        [(crate::statement::NEED_PROGRAM, MEMBER.to_owned(), 200)]
    );
    let answer: Value =
        serde_json::from_slice(done.answer.as_deref().expect("the requested list arrived"))
            .expect("the child reply is JSON");
    assert_eq!(answer["id"], json!(91));
    assert_eq!(answer["result"]["tools"][0]["name"], "read");
    let state = host.0.borrow();
    let methods: Vec<_> = state.written.iter().map(|v| v["method"].as_str()).collect();
    assert_eq!(
        methods,
        [
            Some("initialize"),
            Some("notifications/initialized"),
            Some("tools/list")
        ]
    );
    assert_eq!(state.closed, [STREAM]);
    assert_eq!(
        state.opened,
        [(crate::statement::NEED_PROGRAM, MEMBER.to_owned())]
    );
}

#[test]
fn a_valid_first_launch_receipt_permits_the_actual_program_exchange() {
    positive_control();
}

#[test]
fn an_invalid_first_launch_receipt_closes_before_any_child_write() {
    positive_control();
    let good = receipt(COMMAND);
    let mut duplicate = good.clone();
    duplicate.extend_from_slice(b"generation: 7\r\n");
    for (status, fields) in [
        (403, good.clone()),
        (200, b"generation: 7\r\n".to_vec()),
        (200, receipt("/unapproved/receipt-child")),
        (200, duplicate),
        (
            200,
            b"generation: 07\r\nprogram-instance: 37\r\nprogram-identity: invalid\r\n".to_vec(),
        ),
    ] {
        let host = ScriptedConn::new([Piece::head(status, &fields)]);
        let mut peer = StrictPeer::default();
        let error = exchange(&host, &mut peer).expect_err("the first receipt must authenticate");
        assert_eq!(error, program_trust::UNTRUSTED);
        assert_eq!(peer.checked.len(), 1);
        assert!(peer.greeted.is_empty());
        let state = host.0.borrow();
        assert!(
            state.written.is_empty(),
            "an untrusted lease received a child write"
        );
        assert_eq!(state.closed, [STREAM]);
    }
}

#[test]
fn a_repeated_head_cannot_replace_the_checked_launch_receipt() {
    positive_control();
    let host = ScriptedConn::new([
        Piece::head(200, &receipt(COMMAND)),
        Piece::head(200, &receipt(COMMAND)),
    ]);
    let mut peer = StrictPeer::default();
    let error = exchange(&host, &mut peer).expect_err("a lease has only one host head");
    assert_eq!(error, program_trust::REPEATED);
    assert_eq!(peer.checked.len(), 1, "a later head must not be restamped");
    assert!(peer.greeted.is_empty());
    let state = host.0.borrow();
    assert_eq!(state.closed, [STREAM]);
    assert_eq!(state.written.len(), 1);
    assert_eq!(state.written[0]["method"], "initialize");
}

#[test]
fn child_body_before_the_first_head_closes_without_parsing_or_writing() {
    positive_control();
    let host = ScriptedConn::new([
        Piece::body(&json!({ "jsonrpc": "2.0", "id": 91, "result": { "tools": [] } })),
        Piece::head(200, &receipt(COMMAND)),
    ]);
    let mut peer = StrictPeer::default();
    let error =
        exchange(&host, &mut peer).expect_err("child output cannot stand in for a host head");
    assert_eq!(error, crate::tool_program::CLOSED);
    assert!(peer.checked.is_empty());
    assert!(peer.greeted.is_empty());
    let state = host.0.borrow();
    assert!(state.written.is_empty());
    assert_eq!(state.closed, [STREAM]);
}

#[test]
fn a_numberless_complete_host_receipt_permits_the_program_exchange() {
    let host = ScriptedConn::new([Piece::head(0, &receipt(COMMAND))]);
    let mut peer = StrictPeer::default();
    let done =
        exchange(&host, &mut peer).expect("the actual process contract carries no numeric status");
    assert!(done.greeted);
    assert_ne!(done.generation, 0);
    assert_eq!(peer.greeted, [done.generation]);
    assert_eq!(
        peer.checked,
        [(crate::statement::NEED_PROGRAM, MEMBER.to_owned(), 0)]
    );
    let state = host.0.borrow();
    let methods: Vec<_> = state.written.iter().map(|v| v["method"].as_str()).collect();
    assert_eq!(
        methods,
        [
            Some("initialize"),
            Some("notifications/initialized"),
            Some("tools/list")
        ]
    );
    assert_eq!(state.closed, [STREAM]);
}
